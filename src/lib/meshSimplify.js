// 102 M1 — SIMPLIFY ANY MESH, as a PURE function over indexed geometry data.
//
// No THREE, no scene, no store: a geometry arrives as named typed arrays and leaves the same
// way, so the mesh kernel (roadmap 99 K4) can adopt it unchanged and the unit suite runs it in
// node against the REAL simplifier. The arithmetic is the import reducer's
// (`decimateCore.simplifyMesh`, meshoptimizer's quadric simplifier handed in) — one reducer in
// the app, not two; this module only decides which channels it WEIGHS and which it CARRIES.
//
//  · weighed: position, normal, uv, color (Float32 only — a quantized channel is carried)
//  · carried: every other per-vertex channel (skinIndex / skinWeight, uv1, uv2 …). The
//    simplifier collapses onto EXISTING vertices, so a kept vertex keeps its own weights.
//  · dropped: `tangent` (it described the old triangles; three regenerates it) — reported.
//  · material groups are simplified separately with their borders locked (decimateCore), so
//    no triangle changes slot and no seam opens between slots.
import { simplifyMesh } from './decimateCore';

/**
 * @typedef {{array: ArrayLike<number> & {length: number}, itemSize: number, normalized?: boolean}} Channel
 * @typedef {{attributes: Record<string, Channel>, index: Uint32Array | null,
 *   groups: {start: number, count: number, materialIndex?: number}[]}} GeometryData
 * @typedef {{data: GeometryData, before: number, triangles: number, error: number,
 *   recomputeNormals: boolean, dropped: string[]}} SimplifyResult
 */

/** Channels the simplifier weighs, by attribute name → decimateCore's MeshIn key. */
const WEIGHED = /** @type {const} */ ({ normal: 'normals', uv: 'uvs', color: 'colors' });
/** Channels that cannot survive a change of triangles and are regenerated by three. */
export const DROPPED_CHANNELS = ['tangent'];
/** The smallest result offered: below this a mesh stops being a shape. */
export const MIN_TRIANGLES = 4;

/** Triangles in a geometry's data. @param {GeometryData} data */
export function trianglesIn(data) {
	const position = data.attributes.position;
	if (!position) return 0;
	return Math.floor((data.index ? data.index.length : position.array.length / position.itemSize) / 3);
}

/**
 * The triangle target for a request: `percent` (1-100) of `before`, or an absolute `triangles`.
 * Clamped to [MIN_TRIANGLES, before]; a request at or above `before` returns `before` (= nothing to do).
 * @param {number} before @param {{percent?: number, triangles?: number}} want @returns {number}
 */
export function simplifyTarget(before, want) {
	if (!(before > 0)) return 0;
	let target = before;
	if (Number.isFinite(want?.triangles)) target = Math.round(Number(want.triangles));
	else if (Number.isFinite(want?.percent)) target = Math.round((before * Number(want.percent)) / 100);
	return Math.max(Math.min(MIN_TRIANGLES, before), Math.min(before, target));
}

/** Is this channel a plain float one the simplifier can weigh? @param {Channel | undefined} c @param {number} size */
function weighable(c, size) {
	return !!c && c.array instanceof Float32Array && c.itemSize === size && !c.normalized;
}

/**
 * Build the reducer's job from geometry data. PURE.
 * @param {GeometryData} data @param {number} target @param {{key?: string, errorCap?: number}} [opts]
 */
export function simplifyJob(data, target, opts = {}) {
	const attrs = data.attributes;
	/** @type {any} */
	const job = {
		key: opts.key ?? '0',
		positions: Float32Array.from(attrs.position.array),
		index: data.index ? Uint32Array.from(data.index) : null,
		groups: (data.groups ?? []).map((g) => ({ start: g.start, count: g.count, ...(g.materialIndex !== undefined ? { materialIndex: g.materialIndex } : {}) })),
		target,
		errorCap: opts.errorCap ?? 1,
		// a seam / pole / real hole must not slide: two sides simplified apart crack open (measured: a
		// uv sphere at 25 % left 67 open edges along its seam without it)
		lockBorder: true,
		extras: []
	};
	/** @type {string[]} */
	const dropped = [];
	for (const [name, channel] of Object.entries(attrs)) {
		if (name === 'position') continue;
		if (DROPPED_CHANNELS.includes(name)) {
			dropped.push(name);
			continue;
		}
		const key = /** @type {Record<string, string>} */ (WEIGHED)[name];
		if (key && name === 'color' && weighable(channel, channel.itemSize) && (channel.itemSize === 3 || channel.itemSize === 4)) {
			job.colors = Float32Array.from(channel.array);
			job.colorSize = channel.itemSize;
		} else if (key && name !== 'color' && weighable(channel, name === 'uv' ? 2 : 3)) {
			job[key] = Float32Array.from(channel.array);
		} else {
			const Ctor = /** @type {any} */ (channel.array).constructor ?? Float32Array;
			job.extras.push({ name, array: new Ctor(channel.array), itemSize: channel.itemSize, ...(channel.normalized ? { normalized: true } : {}) });
		}
	}
	if (!job.extras.length) delete job.extras;
	return { job, dropped };
}

/**
 * Turn the reducer's output back into geometry data. PURE.
 * @param {any} out decimateCore MeshOut @param {string[]} dropped
 * @returns {SimplifyResult}
 */
export function simplifyResult(out, dropped = []) {
	/** @type {Record<string, Channel>} */
	const attributes = { position: { array: out.positions, itemSize: 3 } };
	if (out.normals) attributes.normal = { array: out.normals, itemSize: 3 };
	if (out.uvs) attributes.uv = { array: out.uvs, itemSize: 2 };
	if (out.colors) attributes.color = { array: out.colors, itemSize: out.colorSize ?? 3 };
	for (const extra of out.extras ?? []) attributes[extra.name] = { array: extra.array, itemSize: extra.itemSize, ...(extra.normalized ? { normalized: true } : {}) };
	return {
		data: { attributes, index: out.index, groups: out.groups ?? [] },
		before: out.before,
		triangles: out.triangles,
		error: out.error,
		recomputeNormals: !!out.recomputeNormals,
		dropped
	};
}

/**
 * Simplify one geometry towards `want` — PURE apart from the handed-in simplifier
 * (meshoptimizer's `MeshoptSimplifier`, ready). The target is the user's, so the error cap is
 * lifted: the count is what was asked for, and the error actually introduced is reported.
 * @param {any} simplifier @param {GeometryData} data @param {{percent?: number, triangles?: number}} want
 * @returns {SimplifyResult}
 */
export function simplifyGeometryData(simplifier, data, want) {
	const before = trianglesIn(data);
	const target = simplifyTarget(before, want);
	const { job, dropped } = simplifyJob(data, target);
	return simplifyResult(simplifyMesh(simplifier, job), dropped);
}

/**
 * Why an object cannot be simplified, or '' when it can. PURE over plain facts, so the menu, the
 * agent tool and the suite agree. `parametric` = a primitive whose Geometry rows still drive it.
 * @param {{mesh?: boolean, instanced?: boolean, scatter?: boolean, parametric?: boolean, morph?: boolean, triangles?: number, vrm?: boolean, carrier?: string}} f
 */
export function simplifyRefusal(f) {
	// 102-int-2: a decal / splat is rebuilt from its record (its mesh is a placeholder or a proxy box)
	if (f.carrier === 'decal') return 'A decal follows the surface under it — simplify that object instead.';
	if (f.carrier === 'splat') return 'A Gaussian splat is not a mesh — use Crop in the Splat section, or a splat editor.';
	if (f.scatter || f.instanced) return 'This is an instanced scatter — simplify its source object instead.';
	if (!f.mesh) return 'Nothing to simplify: pick a mesh or an imported model.';
	if (f.parametric) return 'This shape is still parametric (its Geometry settings drive it). Bake it to a mesh first.';
	if (f.vrm) return 'VRM avatars keep their own format — simplify the model in a VRM tool.';
	if (f.morph) return 'This mesh has morph targets (shape keys), which would not survive simplifying.';
	if ((f.triangles ?? 0) <= MIN_TRIANGLES) return 'This mesh is already as simple as it gets.';
	return '';
}

/** The sorted attribute names of geometry data (the suite's "same attribute set" check). @param {GeometryData} data */
export function attributeNames(data) {
	return Object.keys(data.attributes).sort();
}
