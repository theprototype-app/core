#!/usr/bin/env node
// CLAUDE-index.md — A TABLE OF CONTENTS FOR CLAUDE.md, BY LINE.
//
// CLAUDE.md is ~7,000 lines (500 KB) of architecture map and gotchas, and an agent is shown only its
// first screen. Nobody reads it whole, so what it knows is found by luck or by an expensive grep across
// the whole file. The index is one line per entry — every `## ` section, every top-level `- ` bullet and
// every bold sub-entry (`  · **…**`, `  **…**`) — with the line it starts on, so a reader greps the
// index for a word, then reads CLAUDE.md at that offset.
//
//   node scripts/claude-index.cjs           # write CLAUDE-index.md
//   node scripts/claude-index.cjs --check   # exit 1 when CLAUDE-index.md is not what this would write
//
// Generated, never edited: a merge conflict in it is resolved by running this again.

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'CLAUDE.md');
const OUT = path.join(ROOT, 'CLAUDE-index.md');

/** the entry's name: its bold lead if it has one, else its first words @param {string} text */
function title(text) {
	const bold = /^\*\*(.+?)\*\*/.exec(text);
	const t = bold ? bold[1] : text;
	const flat = t.replace(/\s+/g, ' ').trim();
	return flat.length > 110 ? flat.slice(0, 107).replace(/\s+\S*$/, '') + ' …' : flat;
}

/** @param {string} md @returns {string} */
function build(md) {
	const lines = md.split('\n');
	const out = [
		'# CLAUDE-index.md — where things are in CLAUDE.md',
		'',
		'Generated by `node scripts/claude-index.cjs` (never edit; on a merge conflict, run it again).',
		'Grep this file for a word, then read CLAUDE.md from that line (`Read CLAUDE.md offset=<line> limit=60`).',
		`${lines.length} lines indexed.`,
		''
	];
	lines.forEach((l, i) => {
		const n = String(i + 1).padStart(5);
		let m;
		if ((m = /^(#{1,3}) (.+)/.exec(l))) out.push(`${m[1].length === 1 ? '' : '\n'}${n}  ${m[1]} ${m[2].trim()}`);
		else if ((m = /^- (.+)/.exec(l))) out.push(`${n}  - ${title(m[1])}`);
		else if ((m = /^ {2}(?:· )?(\*\*.+)/.exec(l))) out.push(`${n}      · ${title(m[1])}`);
	});
	return out.join('\n') + '\n';
}

if (require.main === module) {
	const want = build(fs.readFileSync(SRC, 'utf8'));
	if (process.argv.includes('--check')) {
		const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
		if (have !== want) {
			console.error('CLAUDE-index.md is stale: run node scripts/claude-index.cjs');
			process.exit(1);
		}
		console.log('CLAUDE-index.md is current');
	} else {
		fs.writeFileSync(OUT, want);
		console.log(`CLAUDE-index.md: ${want.split('\n').length} lines for ${mdLines()} lines of CLAUDE.md`);
	}
}

function mdLines() {
	return fs.readFileSync(SRC, 'utf8').split('\n').length;
}

module.exports = { build, title };
